def format_item_custom_moves(party_name, group_comment, mons):
    assert len(mons) == 6, f"{party_name} must have 6 mons, got {len(mons)}"
    lines = [f"static const struct TrainerMonItemCustomMoves {party_name}[] = {{ //{group_comment}"]
    for m in mons:
        iv, lvl, sp, item, moves = m
        assert sp in valid_species, f"Invalid species {sp} in {party_name}"
        assert item in valid_items, f"Invalid item {item} in {party_name}"
        assert len(moves) == 4, f"{party_name} {sp} must have 4 moves"
        for mv in moves:
            assert mv in valid_moves, f"Invalid move {mv} in {party_name}"
        lines.append("    {")
        lines.append(f"    .iv = {iv},")
        lines.append(f"    .lvl = {lvl},")
        lines.append(f"    .species = {sp},")
        lines.append(f"    .heldItem = {item},")
        lines.append(f"    .moves = {{{', '.join(moves)}}}")
        lines.append("    },")
    lines.append("};\n")
    return "\n".join(lines)

def format_no_item_default_moves(party_name, group_comment, mons):
    lines = [f"static const struct TrainerMonNoItemDefaultMoves {party_name}[] = {{ //{group_comment}"]
    for iv, lvl, sp in mons:
        assert sp in valid_species, f"Invalid species {sp} in {party_name}"
        lines.append("    {")
        lines.append(f"    .iv = {iv},")
        lines.append(f"    .lvl = {lvl},")
        lines.append(f"    .species = {sp},")
        lines.append("    },")
    lines.append("};\n")
    return "\n".join(lines)

